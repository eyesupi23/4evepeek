def to_svg(bg, palette, art):
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), "sprite must be 16x16"
    rects = [f'<rect x="{x}" y="{y}" width="1" height="1" fill="{palette[c]}"/>'
             for y, row in enumerate(rows) for x, c in enumerate(row) if c != "."]
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">'
            f'<rect width="16" height="16" fill="{bg}"/>' + "".join(rects) + "</svg>")

OUT.mkdir(parents=True, exist_ok=True)
for name, (bg, pal, art) in SPRITES.items():
    (OUT / f"{name}.svg").write_text(to_svg(bg, pal, art))
    print("wrote", name)
